CREATE TABLE stocks (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  id_produit BIGINT NOT NULL,
  date_appro DATE NOT NULL,
  date_peremp DATE NOT NULL,
  prix_achat_unitaire DECIMAL(10, 2) NOT NULL DEFAULT 0,
  quantite_appro INT NOT NULL,
  prix_vente_unitaire DECIMAL(10, 2) NOT NULL,
  quantite_restante INT NOT NULL,
  FOREIGN KEY (id_produit) REFERENCES produit(id_produit),
  INDEX idx_stocks_produit_peremp (id_produit, date_peremp),
  CHECK (quantite_appro > 0),
  CHECK (
    quantite_restante >= 0
    AND quantite_restante <= quantite_appro
  )
);

